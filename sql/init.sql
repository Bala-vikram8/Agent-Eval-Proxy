-- Model ids like gpt-4o-mini-2024-07-18 are priced as gpt-4o-mini. The model the upstream
-- reports (response_model) is priced when known, otherwise the requested one.
-- failed: the exchange did not complete because of the upstream or the proxy. A caller hanging
-- up (client_disconnect) is not counted as a failure, but is excluded from latency percentiles.
CREATE VIEW traces_enriched AS
SELECT
    t.*,
    coalesce(t.response_model, t.model) AS billed_model,
    (t.prompt_tokens * p.input_usd_per_mtok + t.completion_tokens * p.output_usd_per_mtok) / 1000000.0
        AS cost_usd,
    (t.judge_prompt_tokens * jp.input_usd_per_mtok + t.judge_completion_tokens * jp.output_usd_per_mtok) / 1000000.0
        AS judge_cost_usd,
    (t.status_code = 200 AND t.prompt_tokens IS NOT NULL AND p.model IS NULL) AS unpriced,
    (t.status_code = 200 AND t.prompt_tokens IS NULL) AS usage_missing,
    (t.status_code IS DISTINCT FROM 200 OR coalesce(t.error_type, '') LIKE 'upstream%') AS failed,
    (t.status_code = 200 AND t.error_type IS NULL) AS completed
FROM traces t
LEFT JOIN model_prices p
       ON p.model = regexp_replace(coalesce(t.response_model, t.model), '-\d{4}-\d{2}-\d{2}$', '')
LEFT JOIN model_prices jp
       ON jp.model = regexp_replace(t.judge_model, '-\d{4}-\d{2}-\d{2}$', '');

CREATE VIEW trace_summary AS
SELECT
    count(*)                                                        AS traces,
    count(*) FILTER (WHERE failed)                                  AS errors,
    round(100.0 * count(*) FILTER (WHERE failed)
          / nullif(count(*), 0), 1)                                 AS error_rate_pct,
    count(*) FILTER (WHERE error_type = 'client_disconnect')        AS client_disconnects,
    round((percentile_cont(0.5)  WITHIN GROUP (ORDER BY latency_ms)
           FILTER (WHERE completed))::numeric)                      AS p50_latency_ms,
    round((percentile_cont(0.95) WITHIN GROUP (ORDER BY latency_ms)
           FILTER (WHERE completed))::numeric)                      AS p95_latency_ms,
    round((percentile_cont(0.5)  WITHIN GROUP (ORDER BY ttft_ms)
           FILTER (WHERE streamed AND completed))::numeric)         AS p50_ttft_ms,
    round((percentile_cont(0.95) WITHIN GROUP (ORDER BY ttft_ms)
           FILTER (WHERE streamed AND completed))::numeric)         AS p95_ttft_ms,
    round((percentile_cont(0.95) WITHIN GROUP (ORDER BY
           extract(epoch FROM ingested_at - created_at) * 1000)
           FILTER (WHERE ingested_at IS NOT NULL))::numeric)         AS p95_ingest_delay_ms,
    count(*) FILTER (WHERE usage_missing)                           AS usage_missing,
    count(*) FILTER (WHERE redaction_count > 0)                     AS redacted_traces,
    count(*) FILTER (WHERE streamed)                                AS streamed,
    coalesce(sum(cost_usd), 0)                                      AS model_cost_usd,
    coalesce(sum(judge_cost_usd), 0)                                AS judge_cost_usd,
    count(*) FILTER (WHERE unpriced)                                AS unpriced_traces,
    avg(relevance_score)                                            AS avg_relevance,
    count(*) FILTER (WHERE eval_status = 'scored')                  AS eval_scored,
    count(*) FILTER (WHERE eval_status = 'skipped')                 AS eval_skipped,
    count(*) FILTER (WHERE eval_status = 'failed')                  AS eval_failed,
    count(*) FILTER (WHERE eval_status IN ('pending', 'running'))   AS eval_pending
FROM traces_enriched;

-- requested model, and the model that actually served it according to the upstream.
CREATE VIEW model_summary AS
SELECT
    model,
    response_model,
    count(*)                                                        AS traces,
    count(*) FILTER (WHERE failed)                                  AS errors,
    round((percentile_cont(0.5) WITHIN GROUP (ORDER BY latency_ms)
           FILTER (WHERE completed))::numeric)                      AS p50_latency_ms,
    sum(prompt_tokens)                                              AS prompt_tokens,
    sum(completion_tokens)                                          AS completion_tokens,
    round(sum(cost_usd), 6)                                         AS cost_usd,
    bool_or(unpriced)                                               AS unpriced,
    round(avg(relevance_score), 2)                                  AS avg_relevance,
    count(relevance_score)                                          AS scored
FROM traces_enriched
GROUP BY model, response_model
ORDER BY traces DESC;

-- Queue health per evaluation type: what is waiting and for how long.
CREATE VIEW eval_backlog AS
SELECT 'relevance'::text AS eval_type,
       count(*) FILTER (WHERE eval_status = 'pending')              AS pending,
       count(*) FILTER (WHERE eval_status = 'running')              AS running,
       count(*) FILTER (WHERE eval_status = 'running' AND eval_lease_until < now()) AS expired_leases,
       extract(epoch FROM now() - min(created_at) FILTER (WHERE eval_status IN ('pending', 'running')))::bigint
                                                                    AS oldest_pending_seconds
FROM traces
UNION ALL
SELECT 'grounded',
       count(*) FILTER (WHERE status = 'pending'),
       count(*) FILTER (WHERE status = 'running'),
       count(*) FILTER (WHERE status = 'running' AND lease_until < now()),
       extract(epoch FROM now() - min(created_at) FILTER (WHERE status IN ('pending', 'running')))::bigint
FROM trace_evaluations;

CREATE VIEW evaluation_summary AS
SELECT eval_type, status, verdict, count(*) AS evaluations,
       count(*) FILTER (WHERE needs_review) AS needs_review,
       sum(judge_prompt_tokens) AS judge_prompt_tokens,
       sum(judge_completion_tokens) AS judge_completion_tokens
FROM trace_evaluations
GROUP BY eval_type, status, verdict
ORDER BY eval_type, status, verdict;

CREATE VIEW review_summary AS
SELECT
    count(*)                                                        AS reviews,
    count(*) FILTER (WHERE status = 'pending')                      AS pending,
    count(*) FILTER (WHERE status = 'approved')                     AS approved,
    count(*) FILTER (WHERE status = 'rejected')                     AS rejected,
    count(*) FILTER (WHERE status = 'resolved')                     AS resolved,
    extract(epoch FROM now() - min(created_at) FILTER (WHERE status = 'pending'))::bigint
                                                                    AS oldest_pending_seconds,
    round((percentile_cont(0.5) WITHIN GROUP (ORDER BY extract(epoch FROM decided_at - created_at))
           FILTER (WHERE decided_at IS NOT NULL))::numeric)          AS p50_seconds_to_decision
FROM review_items;
