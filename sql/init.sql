-- Evidence grounded evaluations -------------------------------------------------------
-- One row per (trace, evaluation type). Relevance stays on traces for compatibility; newer
-- evaluation types live here because they have richer, versioned results. Named
-- trace_evaluations because the first version of this project created an unrelated
-- "evaluations" table that upgraded databases may still have.

CREATE TABLE IF NOT EXISTS trace_evaluations (
    id                      BIGSERIAL PRIMARY KEY,
    trace_id                INTEGER NOT NULL REFERENCES traces (id) ON DELETE CASCADE,
    eval_type               TEXT NOT NULL,
    status                  TEXT NOT NULL DEFAULT 'pending'
                            CHECK (status IN ('pending', 'running', 'completed', 'skipped', 'failed')),
    attempts                INTEGER NOT NULL DEFAULT 0,
    next_attempt_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    lease_until             TIMESTAMPTZ,
    claim_token             TEXT,
    verdict                 TEXT CHECK (verdict IN ('supported', 'unsupported', 'contradicted',
                                                    'insufficient_evidence', 'incomplete')),
    addresses_request       BOOLEAN,
    needs_review            BOOLEAN,
    result                  JSONB,
    rubric_version          TEXT,
    judge_model             TEXT,
    judge_prompt_tokens     INTEGER,
    judge_completion_tokens INTEGER,
    error                   TEXT,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at            TIMESTAMPTZ,
    UNIQUE (trace_id, eval_type)
);
CREATE INDEX IF NOT EXISTS trace_evaluations_queue_idx ON trace_evaluations (id) WHERE status IN ('pending', 'running');

-- Human review --------------------------------------------------------------------------
-- A review item is opened for an evaluation whose finding needs a person. Review happens
-- after the fact: the original response has already reached its caller.

CREATE TABLE IF NOT EXISTS review_items (
    id              BIGSERIAL PRIMARY KEY,
    trace_id        INTEGER NOT NULL REFERENCES traces (id) ON DELETE CASCADE,
    evaluation_id   BIGINT NOT NULL UNIQUE REFERENCES trace_evaluations (id) ON DELETE CASCADE,
    case_ref        TEXT,
    status          TEXT NOT NULL DEFAULT 'pending'
                    CHECK (status IN ('pending', 'approved', 'rejected', 'resolved')),
    reason          TEXT NOT NULL,
    findings        JSONB NOT NULL,
    version         INTEGER NOT NULL DEFAULT 1,
    decided_by      TEXT,
    decided_at      TIMESTAMPTZ,
    decision_note   TEXT,
    resolved_by     TEXT,
    resolved_at     TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS review_items_status_idx ON review_items (status);

CREATE TABLE IF NOT EXISTS review_events (
    id          BIGSERIAL PRIMARY KEY,
    review_id   BIGINT NOT NULL REFERENCES review_items (id) ON DELETE CASCADE,
    from_status TEXT,
    to_status   TEXT NOT NULL,
    actor       TEXT NOT NULL,
    note        TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- The audit trail is append only. Deletes are still possible through retention cascades.
CREATE OR REPLACE FUNCTION review_events_append_only() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'review_events is append only';
END $$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS review_events_no_update ON review_events;
CREATE TRIGGER review_events_no_update BEFORE UPDATE ON review_events
    FOR EACH ROW EXECUTE FUNCTION review_events_append_only();

