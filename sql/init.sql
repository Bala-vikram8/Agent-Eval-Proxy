-- Retention: deletes traces older than the given number of days, with their evaluations,
-- reviews and review history. Destructive; the worker only calls it when RETENTION_DAYS > 0.
CREATE OR REPLACE FUNCTION purge_traces_older_than(days INTEGER) RETURNS BIGINT AS $$
DECLARE
    removed BIGINT;
BEGIN
    IF days IS NULL OR days < 1 THEN
        RAISE EXCEPTION 'retention must be at least one day';
    END IF;
    DELETE FROM traces WHERE created_at < now() - make_interval(days => days);
    GET DIAGNOSTICS removed = ROW_COUNT;
    RETURN removed;
END $$ LANGUAGE plpgsql;

